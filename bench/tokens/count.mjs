// The offline token baseline (ADR-023): what the TypeScript MCP server hands a model, measured from
// the golden sessions in bench/tokens/golden/mcp/. Text costs ceil(chars / 4) tokens; an image
// costs ceil(width / 28) x ceil(height / 28) visual tokens
// (https://platform.claude.com/docs/en/build-with-claude/vision, 1280x800 is under both tiers'
// limits, so it is not downscaled). Writes baseline.json and baseline.md beside this file.
//
// `--after` (P4) also reads the Rust Bridge's sessions in golden-after/mcp/ (written by
// `cargo test -p vexdom --test mcp_bench -- --ignored` from `capture.mjs --after` pages) and adds a
// before/after table to baseline.md.
import { readFileSync, writeFileSync } from 'node:fs';

const here = (path) => new URL(path, import.meta.url);
const golden = here('golden/');
const FIXTURES = JSON.parse(readFileSync(new URL('pages/index.json', golden), 'utf8')).map((entry) => entry.fixture);

/** The replies of one session, by request id. */
function replies(session, dir = golden) {
  const byId = new Map();
  for (const line of readFileSync(new URL(`mcp/${session}.jsonl`, dir), 'utf8').split('\n')) {
    if (!line.startsWith('< ')) continue;
    const message = JSON.parse(line.slice(2));
    if (typeof message.id === 'number') byId.set(message.id, message);
  }
  return byId;
}

const text = (value) => ({ chars: value.length, tokens: Math.ceil(value.length / 4) });
const textOf = (reply) =>
  reply.result.content
    .filter((block) => block.type === 'text')
    .map((block) => block.text)
    .join('\n');
const image = (width, height) => ({ width, height, tokens: Math.ceil(width / 28) * Math.ceil(height / 28) });

const catalog = replies('catalog');
const baseline = {
  method: 'text: ceil(chars / 4); image: ceil(width / 28) * ceil(height / 28)',
  catalog: {
    tools: text(JSON.stringify(catalog.get(2).result.tools)),
    instructions: text(catalog.get(1).result.instructions),
  },
  fixtures: Object.fromEntries(
    FIXTURES.map((fixture) => {
      const calls = replies(`calls-${fixture}`);
      return [fixture, { getPageInfo: text(textOf(calls.get(2))), extractText: text(textOf(calls.get(3))) }];
    }),
  ),
};
const shot = JSON.parse(readFileSync(new URL('pages/firefox_forms/screenshot.json', golden), 'utf8'));
baseline.screenshot = { image: image(shot.width, shot.height), text: text(textOf(replies('calls-firefox_forms').get(4))) };

writeFileSync(here('baseline.json'), JSON.stringify(baseline, null, 2) + '\n');

const rows = [
  ['catalog: tools/list', baseline.catalog.tools],
  ['catalog: server instructions', baseline.catalog.instructions],
  ...FIXTURES.flatMap((fixture) => [
    [`${fixture}: page_getPageInfo`, baseline.fixtures[fixture].getPageInfo],
    [`${fixture}: page_extractText`, baseline.fixtures[fixture].extractText],
  ]),
  [`screenshot: image ${shot.width}×${shot.height}`, { chars: null, tokens: baseline.screenshot.image.tokens }],
  ['screenshot: note text', baseline.screenshot.text],
];
const md = [
  '# Token baseline (TypeScript reference, offline)',
  '',
  'Generated by `bun bench/tokens/count.mjs` from `bench/tokens/golden/mcp/*.jsonl`; do not edit.',
  '',
  `Method: ${baseline.method} (https://platform.claude.com/docs/en/build-with-claude/vision).`,
  'Pages: `bench/tokens/golden/pages/index.json`. Live `claude -p` usage: measured in P4.',
  'getPageInfo is captured as the content script returns it: `pageInfoWithSiteTools` (packages/extension/src/lib/bridge/site-tools.ts)',
  'adds `captcha`, `siteTools` and frame focus only when the page has them; capture.mjs runs only the',
  'content-script action, so `webmcp_probe` is measured without the `siteTools` the extension would add.',
  '',
  '| What the model receives | Chars | Tokens |',
  '| --- | ---: | ---: |',
  ...rows.map(([what, { chars, tokens }]) => `| ${what} | ${chars ?? '—'} | ${tokens} |`),
  '',
];
writeFileSync(here('baseline.md'), md.join('\n'));

if (process.argv.includes('--after')) {
  const goldenAfter = here('golden-after/');
  /** A session's replies in the order they came, for sessions whose ids run on from the last one. */
  const ordered = (session) => [...replies(session, goldenAfter).values()];
  const catalogAfter = ordered('catalog');
  const init = catalogAfter.find((reply) => reply.result?.instructions !== undefined);
  const list = catalogAfter.find((reply) => Array.isArray(reply.result?.tools));
  const after = {
    catalog: { tools: text(JSON.stringify(list.result.tools)), instructions: text(init.result.instructions) },
    fixtures: Object.fromEntries(
      FIXTURES.map((fixture) => {
        const [snapshot, read, outline, delta] = ordered(`calls-${fixture}`);
        return [
          fixture,
          {
            snapshot: text(textOf(snapshot)),
            read: text(textOf(read)),
            outline: text(textOf(outline)),
            ...(delta ? { delta: text(textOf(delta)) } : {}),
          },
        ];
      }),
    ),
  };
  writeFileSync(here('baseline-after.json'), JSON.stringify(after, null, 2) + '\n');
  const change = (before, now) => `${Math.round(((now - before) / before) * 100)}%`;
  const pair = (what, before, now) => `| ${what} | ${before.tokens} | ${now.tokens} | ${change(before.tokens, now.tokens)} |`;
  const table = [
    '## Before / after (Rust Bridge, 3-tool MCP (ADR-029))',
    '',
    'Before: the TypeScript MCP server (rows above). After: `vexdom mcp` (Rust) from',
    '`bench/tokens/golden-after/mcp/*.jsonl`. Probe fixtures are static; the three real pages were',
    'captured again for the after run, so their content drifted from the before capture.',
    'Snapshots are interactive (`snapshot`, as: tree, default); read is `snapshot` as: markdown; outline is headings only.',
    '',
    '| What the model receives | Before (tokens) | After (tokens) | Change |',
    '| --- | ---: | ---: | ---: |',
    pair('catalog: tools/list', baseline.catalog.tools, after.catalog.tools),
    pair('catalog: server instructions', baseline.catalog.instructions, after.catalog.instructions),
    ...FIXTURES.flatMap((fixture) => {
      const before = baseline.fixtures[fixture];
      const now = after.fixtures[fixture];
      return [
        pair(`${fixture}: page_getPageInfo → snapshot`, before.getPageInfo, now.snapshot),
        pair(`${fixture}: page_extractText → snapshot as:markdown`, before.extractText, now.read),
        `| ${fixture}: snapshot as:markdown outline | — | ${now.outline.tokens} | |`,
        ...(now.delta ? [`| ${fixture}: snapshot after typing (delta) | — | ${now.delta.tokens} | |`] : []),
      ];
    }),
    '',
  ];
  writeFileSync(here('baseline.md'), [...md, ...table].join('\n'));
}
